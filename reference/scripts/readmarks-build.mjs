// Builds src/lib/readmarks/spec.generated.ts from content/protocols so the served bytes, their SHA-256, the rendered page,
// the origin registry and the reading-check questions all come from one place. Run by `npm run build`.
import fs from 'node:fs';
import crypto from 'node:crypto';
const sha = (s) => crypto.createHash('sha256').update(Buffer.from(s, 'utf8')).digest('hex');
const docs = [
  { id: 'readmarks-1.0', file: 'content/protocols/readmarks-1.0.md', questions: 'content/protocols/readmarks-1.0.questions.json',
    url: 'https://www.sgai.sg/protocols/readmarks/1.0.md', page: 'https://www.sgai.sg/protocols/readmarks/1.0', version: '1.0', title: 'Readmarks 1.0' },
  { id: 'apo-1.0', file: 'content/protocols/apo-1.0.md', questions: 'content/protocols/apo-1.0.questions.json',
    url: 'https://www.sgai.sg/protocols/apo/1.0.md', page: 'https://www.sgai.sg/protocols/apo/1.0', version: '1.0', title: 'APO 1.0: Agent Preference Optimization' },
].filter((d) => fs.existsSync(d.file));

// Every published article accepts Readmarks too. Its exact bytes (the article source) are served at /readmarks/1/d/<id>.md.
const fm = (raw) => { const m = /^---\n([\s\S]*?)\n---/.exec(raw); const o = {}; if (m) for (const l of m[1].split('\n')) { const k = /^(\w+):\s*(.*)$/.exec(l); if (k) o[k[1]] = k[2].replace(/^["']|["']$/g, ''); } return o; };
const articles = [];
for (const loc of fs.readdirSync('content/blog')) {
  if (!fs.statSync(`content/blog/${loc}`).isDirectory()) continue;
  for (const f of fs.readdirSync(`content/blog/${loc}`).filter((x) => x.endsWith('.mdx'))) articles.push({ id: `blog-${loc}-${f.slice(0, -4)}`, file: `content/blog/${loc}/${f}`, loc, slug: f.slice(0, -4) });
}
for (const f of fs.readdirSync('content/world-ai/posts').filter((x) => x.endsWith('.mdx'))) articles.push({ id: `world-ai-${f.slice(0, -4)}`, file: `content/world-ai/posts/${f}`, loc: 'en', slug: f.slice(0, -4) });
const reports = fs.existsSync('content/readmarks/reports') ? fs.readdirSync('content/readmarks/reports').filter((x) => x.endsWith('.md')) : [];
for (const f of reports) articles.push({ id: `report-${f.slice(0, -3)}`, file: `content/readmarks/reports/${f}`, loc: 'en', slug: f.slice(0, -3), report: true });
let stale = 0;
for (const a of articles) {
  const raw = fs.readFileSync(a.file, 'utf8'), m = fm(raw);
  if (m.draft === 'true' || m.status === 'draft') continue;
  if (!a.report && m.slug && m.slug !== a.slug) { a.slug = m.slug; a.id = `${a.id.startsWith('world-ai-') ? 'world-ai' : `blog-${a.loc}`}-${m.slug}`; } // the route uses the frontmatter slug
  const qfile = `content/readmarks/questions/${a.id}.json`;
  const bank = fs.existsSync(qfile) ? JSON.parse(fs.readFileSync(qfile, 'utf8')) : null;
  if (!bank || bank.sourceSha256 !== sha(raw)) { stale++; console.log(`readmarks: NO CURRENT QUESTIONS for ${a.id} (run scripts/readmarks-questions.py); it will not issue tickets`); }
  docs.push({ id: a.id, file: a.file, bank: bank && bank.sourceSha256 === sha(raw) ? bank.questions : [], kind: a.report ? 'report' : 'article',
    url: `https://www.sgai.sg/readmarks/1/d/${encodeURIComponent(a.id)}.md`, page: a.report ? `https://www.sgai.sg/en/intelligence/${a.slug}` : `https://www.sgai.sg/${a.loc}/blog/${encodeURIComponent(a.slug)}`,
    version: m.date || '1', title: m.title || a.slug });
}
const out = [], questions = {}, qsha = {};
for (const d of docs) {
  const md = fs.readFileSync(d.file, 'utf8');
  out.push({ id: d.id, kind: d.kind ?? 'standard', url: d.url, page: d.page, version: d.version, title: d.title, sha256: sha(md), md });
  const bank = d.bank ?? (fs.existsSync(d.questions) ? JSON.parse(fs.readFileSync(d.questions, 'utf8')) : []);
  for (const q of bank) if (!(q.id && q.q && Array.isArray(q.options) && q.options.length === 4 && Number.isInteger(q.answer) && q.answer >= 0 && q.answer < 4)) throw new Error(`bad question ${q.id} in ${d.questions}`);
  questions[d.id] = bank;
  // The public digest covers questions and options only; the answers stay on the server.
  qsha[d.id] = sha(JSON.stringify(bank.map(({ id, q, options }) => ({ id, q, options }))));
}
const origins = fs.readFileSync('content/protocols/readmarks-origins.json', 'utf8');
fs.writeFileSync('src/lib/readmarks/spec.generated.ts',
  '// GENERATED by scripts/readmarks-build.mjs from content/protocols. Do not edit by hand.\n' +
  `export const RM_DOCUMENTS: { id: string; kind: string; url: string; page: string; version: string; title: string; sha256: string; md: string }[] = ${JSON.stringify(out, null, 1)};\n` +
  `export const RM_QUESTIONS: Record<string, { id: string; q: string; options: string[]; answer: number }[]> = ${JSON.stringify(questions)};\n` +
  `export const RM_QUESTIONS_SHA256: Record<string, string> = ${JSON.stringify(qsha)};\n` +
  `export const RM_ORIGINS_RAW = ${JSON.stringify(origins)};\n` +
  `export const RM_ORIGINS_SHA256 = ${JSON.stringify(sha(origins))};\n` +
  'export const RM_ORIGINS = JSON.parse(RM_ORIGINS_RAW);\n');
for (const d of out.filter((x) => x.kind === 'standard')) console.log(`readmarks: ${d.id} sha256 ${d.sha256} · ${questions[d.id].length} questions`);
for (const k of ['article', 'report']) console.log(`readmarks: ${out.filter((x) => x.kind === k).length} ${k}s, ${out.filter((x) => x.kind === k && questions[x.id].length).length} with current questions`);
console.log(`readmarks: origin registry sha256 ${sha(origins)}`);
